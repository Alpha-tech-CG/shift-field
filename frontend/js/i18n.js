  const ORDER = ["fr", "en", "it"];
  const KEY = "fs_lang";
  let lang = localStorage.getItem(KEY) || "fr";
  if (!DICT[lang]) lang = "fr";

  function t(key) {
    return (DICT[lang] && DICT[lang][key]) || DICT.fr[key] || key;
  }

  function apply(root) {
    const r = root || document;
    r.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    r.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    r.querySelectorAll("[data-lang-label]").forEach((el) => {
      el.textContent = lang.toUpperCase();
    });
    document.documentElement.lang = lang;
  }

  function setLang(l) {
    lang = DICT[l] ? l : "fr";
    localStorage.setItem(KEY, lang);
    apply();
    document.dispatchEvent(new CustomEvent("fs:langchange", { detail: { lang } }));
  }

  function cycle() {
    const i = ORDER.indexOf(lang);
    setLang(ORDER[(i + 1) % ORDER.length]);
  }

  window.FSI18N = { t, apply, setLang, cycle, get lang() { return lang; } };
  document.addEventListener("DOMContentLoaded", () => apply());
