  const ORDER = ["fr", "en", "it"];
  const LOCALE = { fr: "fr-FR", en: "en-US", it: "it-IT" };
  const KEY = "fs_lang";
  let lang = "fr";
  try { lang = localStorage.getItem(KEY) || "fr"; } catch (e) {}
  if (!DICT[lang]) lang = "fr";

  function t(key) { return (DICT[lang] && DICT[lang][key]) || DICT.fr[key] || key; }
  function f(key, vars) {
    return t(key).replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] != null ? vars[k] : ""));
  }

  function apply(root) {
    const r = root || document;
    r.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
    r.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
    r.querySelectorAll("[data-lang-label]").forEach((el) => { el.textContent = lang.toUpperCase(); });
    document.documentElement.lang = lang;
  }

  function setLang(l) {
    lang = DICT[l] ? l : "fr";
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    apply();
    document.dispatchEvent(new CustomEvent("fs:langchange", { detail: { lang } }));
  }
  function cycle() { setLang(ORDER[(ORDER.indexOf(lang) + 1) % ORDER.length]); }

